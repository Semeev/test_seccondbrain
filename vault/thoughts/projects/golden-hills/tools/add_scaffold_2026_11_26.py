import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from openpyxl import load_workbook
from wbtools import ensure_v2, ensure_v3, add_positions
X = sys.argv[1]
wb = load_workbook(X); ensure_v2(wb); ensure_v3(wb)
L, St, M = "Леса и подмости", "2. Каркас (монолит)", "Ежемесячно"
items = [(L, n, u, note, St, M) for n, u, note in [
    ("Леса рамные строительные (аренда)", "м²/мес", "Фасадные рамные леса, цена аренды за м² фасада в месяц"),
    ("Леса рамные строительные (покупка)", "м²", "Покупка комплекта, цена за м² фасада"),
    ("Леса клиновые / хомутовые (аренда)", "м²/мес", ""),
    ("Вышка-тура передвижная (аренда)", "сутки", "Высота 4–8 м"),
    ("Стойка телескопическая опалубочная (аренда)", "шт/мес", "Под перекрытия"),
]] + [("Метизы", n, u, note, "9. Метизы и расходники", M) for n, u, note in [
    ("Электроды УОНИ 13/55 d3–4", "кг", ""),
    ("Болт М12 с гайкой и шайбой", "кг", ""),
]]
print("добавлено позиций:", add_positions(wb, items))
wb.save(X)
